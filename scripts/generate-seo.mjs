#!/usr/bin/env node
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { caseItems } from "../src/data.js";
import { insightArticles, solutionPages } from "../src/content.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = path.join(root, "public");
const siteUrl = "https://www.aiinsider.it.com";
const reviewed = "2026-10-05";
const previousReview = "2026-09-07";

const pages = [
  ["/", reviewed],
  ["/services", reviewed],
  ["/cases", previousReview],
  ...caseItems.map((item) => [
    `/cases/${item.slug}`,
    item.updated || item.published || "2026-08-21",
  ]),
  ["/studio", previousReview],
  ["/about", previousReview],
  ["/contact", previousReview],
  ["/solutions", reviewed],
  ["/insights", reviewed],
  ...insightArticles.map((article) => [
    `/insights/${article.slug}`,
    article.updated,
  ]),
  ["/tools/n8n-workflow-library", previousReview],
  ["/tools/ai-automation-calculator", previousReview],
  ...solutionPages.map((solution) => [
    `/solutions/${solution.slug}`,
    solution.updated || previousReview,
  ]),
];

const escapeXml = (value) =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${pages.map(([pathname, lastmod]) => `  <url><loc>${siteUrl}${pathname}</loc><lastmod>${lastmod}</lastmod></url>`).join("\n")}
</urlset>
`;

const feed = `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0">
  <channel>
    <title>AI Insider Insights</title>
    <link>${siteUrl}/insights</link>
    <description>Практичні матеріали про n8n, AI-агентів та автоматизацію бізнесу.</description>
    <language>uk-UA</language>
${insightArticles
  .map(
    (article) => `    <item>
      <title>${escapeXml(article.title)}</title>
      <link>${siteUrl}/insights/${article.slug}</link>
      <guid isPermaLink="true">${siteUrl}/insights/${article.slug}</guid>
      <description>${escapeXml(article.description)}</description>
      <pubDate>${new Date(`${article.published}T12:00:00Z`).toUTCString()}</pubDate>
    </item>`,
  )
  .join("\n")}
  </channel>
</rss>
`;

const llms = `# AI Insider

> AI Insider designs AI agents, business automation, n8n workflows and AI content systems for companies in Ukraine and Switzerland.

Primary language: Ukrainian (uk-UA)
Canonical site: ${siteUrl}

## Core pages
- [Services](${siteUrl}/services)
- [Verified case studies](${siteUrl}/cases)
- [AI Content Studio](${siteUrl}/studio)
- [Insights](${siteUrl}/insights)
- [Contact](${siteUrl}/contact)

## Current research clusters
- [n8n українською](${siteUrl}/insights/n8n-ukrainskoiu)
- [Курс n8n українською](${siteUrl}/insights/n8n-kurs-ukrainskoiu)
- [n8n MCP Server](${siteUrl}/insights/n8n-mcp-server)
- [n8n AI Agent](${siteUrl}/insights/n8n-ai-agent)
- [Google Workspace Studio](${siteUrl}/insights/google-workspace-studio-ukrainskoiu)
- [Gemini Notebook / NotebookLM](${siteUrl}/insights/notebooklm-for-business)

## Reusable assets
- [10 n8n workflow JSON blueprints](${siteUrl}/tools/n8n-workflow-library)
- [AI automation ROI calculator](${siteUrl}/tools/ai-automation-calculator)

## Commercial solutions
- [AI-рекрутер для агенції](${siteUrl}/solutions/ai-recruiter-agency)
- [ШІ-обробка вхідних дзвінків](${siteUrl}/solutions/ai-inbound-call-automation)
- [Автоматизація салону краси](${siteUrl}/solutions/beauty-salon-automation)

Editorial policy: official sources, explicit limitations, review date, measurable process outcomes. No confidential client data is published.
`;

// seo.js runs on every page; it gets article metadata from this slim
// index instead of pulling every article body into the main bundle
const seoIndex = {
  insightArticles: insightArticles.map(
    ({ slug, seoTitle, title, description, published, updated, faq, sources }) => ({
      slug,
      seoTitle,
      title,
      description,
      published,
      updated,
      faq,
      sources,
    }),
  ),
  solutionPages: solutionPages.map(({ slug, seoTitle, title, description, faq }) => ({
    slug,
    seoTitle,
    title,
    description,
    faq,
  })),
};
writeFileSync(
  path.join(root, "src", "seo-index.js"),
  `// Generated by scripts/generate-seo.mjs — do not edit.\n${Object.entries(seoIndex)
    .map(([name, value]) => `export const ${name} = ${JSON.stringify(value, null, 2)};\n`)
    .join("\n")}`,
);
writeFileSync(path.join(publicDir, "sitemap.xml"), sitemap);
writeFileSync(path.join(publicDir, "feed.xml"), feed);
writeFileSync(path.join(publicDir, "llms.txt"), llms);

console.log(
  `Generated SEO discovery files for ${pages.length} indexable URLs.`,
);

// Original, synthetic exercises. No credentials or claimed client results.
const guideDir = path.join(publicDir, "downloads", "guides");
mkdirSync(guideDir, { recursive: true });
for (const article of insightArticles.filter((item) => item.practice)) {
  const exercise = article.practice;
  const lines = [
    `# ${exercise.title}`,
    "",
    `AI Insider · Оновлено ${article.updated}`,
    `Гайд: ${siteUrl}/insights/${article.slug}`,
    "",
    "Навчальне завдання на синтетичних даних. Не результат клієнтського проєкту.",
    "",
    exercise.intro,
    "",
    "## Порядок роботи",
    "",
    ...exercise.steps.map((step, index) => `${index + 1}. ${step}`),
    "",
    ...(exercise.sample
      ? ["## Вхідні дані", "", "```json", exercise.sample, "```", ""]
      : []),
    "## Перевірка",
    "",
    "| Вхід або ситуація | Очікувана поведінка |",
    "| --- | --- |",
    ...exercise.checks.map(([input, expected]) => `| ${input} | ${expected} |`),
    "",
    "## Межі прикладу",
    "",
    exercise.limit,
    "",
    "## Джерела",
    "",
    ...article.sources.map(([label, url]) => `- [${label}](${url})`),
    "",
  ];
  writeFileSync(path.join(guideDir, `${article.slug}.md`), lines.join("\n"));
}
